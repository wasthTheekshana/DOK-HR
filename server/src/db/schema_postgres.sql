  FOREIGN KEY (site_id) REFERENCES sites(id) ON DELETE SET NULL;
ALTER TABLE sites ADD CONSTRAINT fk_site_supervisor
  FOREIGN KEY (supervisor_id) REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE tasks ADD CONSTRAINT fk_task_site
  FOREIGN KEY (site_id) REFERENCES sites(id) ON DELETE CASCADE;
ALTER TABLE tasks ADD CONSTRAINT fk_task_staff
  FOREIGN KEY (staff_id) REFERENCES users(id) ON DELETE CASCADE;
ALTER TABLE attendance ADD CONSTRAINT fk_att_site
  FOREIGN KEY (site_id) REFERENCES sites(id) ON DELETE CASCADE;
ALTER TABLE attendance ADD CONSTRAINT fk_att_staff
  FOREIGN KEY (staff_id) REFERENCES users(id) ON DELETE CASCADE;
